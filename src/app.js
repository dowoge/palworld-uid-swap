/** @type {Map<string, FileEntry>} keyed by lowercased filename */
const files = new Map();
let idSeq = 0;

const HOST_UID = '00000000-0000-0000-0000-000000000001';
const IGNORED = {
  'levelmeta.sav': 'World metadata, regenerated by the game. No player UIDs inside.',
  'localdata.sav': 'Per-machine data (map fog, fast-travel unlocks, markers). No UIDs inside. Each player keeps their own.',
  'worldoption.sav': 'World settings only. No player UIDs inside.',
};

// ---------------------------------------------------------------------------
// UUID helpers
// ---------------------------------------------------------------------------
const isPlayerName = (name) => /^[0-9a-fA-F]{32}\.sav$/.test(name);
const cleanHex = (s) => s.toLowerCase().replace(/[^0-9a-f]/g, '').slice(0, 32);
const hexToDashed = (h) =>
  `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
const filenameToUuid = (name) => hexToDashed(name.replace(/\.sav$/i, '').toLowerCase());
const dashedToFileName = (dashed) => dashed.replace(/-/g, '').toUpperCase() + '.sav';

function fmtSize(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(2)} MB`;
}

const BADGE = {
  PlM: { cls: 'plm', label: 'PlM · Oodle' },
  PlZ: { cls: 'plz', label: 'PlZ · zlib' },
  CNK: { cls: 'cnk', label: 'CNK · zlib' },
};

const uidHtml = (dashed) => dashed;

function friendlyError(err) {
  const m = (err && err.message) || String(err);
  if (/magic|too small to parse|inner magic/i.test(m)) {
    return 'Not a standard .sav container. Xbox / Game Pass saves are wrapped in a different container and .zip archives are not supported. Export a raw Level.sav / Players/*.sav from a Steam/PC save first.';
  }
  if (/Unknown type/i.test(m)) {
    return 'The parser hit a property it does not recognise. This save may be from a much newer or older Palworld version. Please file an issue on GitHub with your game version.';
  }
  return m;
}

