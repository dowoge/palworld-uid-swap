/**
 * @typedef {Object} FileEntry
 * @property {number} id
 * @property {string} name
 * @property {number} size
 * @property {Uint8Array} u8
 * @property {'level'|'player'} kind
 * @property {'parsing'|'ready'|'error'} status
 */

// Reason a file was rejected at intake, phrased for inline display.
function rejectReason(name) {
  const lower = name.toLowerCase();
  if (lower === 'level.sav') return `${name}: this is the world file — use the "Choose Level.sav" picker above.`;
  if (IGNORED[lower]) return `${name}: ${IGNORED[lower]} Not a player save.`;
  return `${name}: not a player save. Player files are named <32 hex characters>.sav.`;
}

// Render a transient list of rejection messages under one control.
function showErrors(el, messages) {
  el.replaceChildren();
  for (const m of messages) {
    const d = document.createElement('div');
    d.className = 'fc-note err';
    d.textContent = m;
    el.appendChild(d);
  }
}

// Read one file, build its entry (replacing any prior file of the same name),
// parse it, and refresh the mapping.
async function ingest(file, kind) {
  const lower = file.name.toLowerCase();
  const buf = new Uint8Array(await file.arrayBuffer());
  const entry = {
    id: ++idSeq, name: file.name, size: file.size, u8: buf,
    kind, status: 'parsing', error: null,
    header: null, gvas: null, slots: null, warnings: [],
    format: null, saveType: null, fileUid: null, uidInFile: false,
    target: '',
  };
  if (kind === 'player') entry.fileUid = filenameToUuid(file.name);
  files.set(lower, entry); // replace any prior file with the same name
  renderFiles();
  await processEntry(entry);
  rebuildMapping();
}

// Level.sav picker: exactly one file, must be named Level.sav.
async function addLevelFile(file) {
  levelErrEl.replaceChildren();
  if (file.name.toLowerCase() !== 'level.sav') {
    showErrors(levelErrEl, [`This picker is only for Level.sav, you selected ${file.name}`]);
    return;
  }
  await ingest(file, 'level'); // same map key replaces any prior Level.sav
}

// Player-saves picker: each file must be a 32-hex-char UID name.
async function addPlayerFiles(fileList) {
  playerErrEl.replaceChildren();
  const errs = [];
  for (const file of fileList) {
    if (isPlayerName(file.name)) await ingest(file, 'player');
    else errs.push(rejectReason(file.name));
  }
  if (errs.length) showErrors(playerErrEl, errs);
}

// Shared drop target: route each dropped file by name, same rules as the pickers.
async function addDropped(fileList) {
  levelErrEl.replaceChildren();
  playerErrEl.replaceChildren();
  const errs = [];
  for (const file of fileList) {
    if (file.name.toLowerCase() === 'level.sav') await ingest(file, 'level');
    else if (isPlayerName(file.name)) await ingest(file, 'player');
    else errs.push(rejectReason(file.name));
  }
  if (errs.length) showErrors(playerErrEl, errs);
}

async function processEntry(entry) {
  try {
    entry.header = parseSavHeader(entry.u8);
    entry.format = entry.header.format;
    const { gvas, format, saveType } = await decompressSav(entry.u8, codec);
    entry.gvas = gvas; entry.format = format; entry.saveType = saveType;
    const { slots, warnings } = findGuidSlots(gvas);
    entry.slots = slots; entry.warnings = warnings;
    if (entry.kind === 'player') {
      entry.uidInFile = slots.some((s) => s.uuid === entry.fileUid);
    }
    entry.status = 'ready';
  } catch (err) {
    entry.status = 'error';
    entry.error = friendlyError(err);
  }
  renderFiles();
}

function removeEntry(id) {
  for (const [k, e] of files) if (e.id === id) { files.delete(k); break; }
  renderFiles();
  rebuildMapping();
}

