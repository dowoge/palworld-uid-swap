function renderFiles() {
  fileListEl.replaceChildren();
  // Order: level first, then players.
  const order = { level: 0, player: 1 };
  const list = [...files.values()].sort((a, b) => order[a.kind] - order[b.kind] || a.name.localeCompare(b.name));

  for (const e of list) {
    const card = document.createElement('div');
    card.className = 'file-card slide-in' + (e.status === 'error' ? ' err' : '');

    const iconCls = e.kind === 'level' ? 'level' : 'player';
    const iconTxt = e.kind === 'level' ? 'LVL' : 'PLYR';

    const badge = e.format && BADGE[e.format]
      ? `<span class="badge ${BADGE[e.format].cls}">${BADGE[e.format].label}</span>` : '';

    let statusHtml = '';
    if (e.status === 'parsing') statusHtml = `<span>reading…</span>`;
    else if (e.status === 'error') statusHtml = `<span class="st-err">✕ error</span>`;
    else if (e.kind === 'player' && !e.uidInFile) statusHtml = `<span class="st-warn">⚠ UID not found</span>`;
    else statusHtml = `<span class="st-ok">✓ ${e.slots ? e.slots.length : 0} slots</span>`;

    let noteHtml = '';
    if (e.status === 'error') noteHtml = `<div class="fc-note err">${escapeHtml(e.error)}</div>`;
    else if (e.kind === 'player' && e.status === 'ready' && !e.uidInFile)
      noteHtml = `<div class="fc-note warn">The filename UID <code>${e.fileUid}</code> was not found among this file's GUID slots. Double-check it's the right Players file.</div>`;
    else if (e.warnings && e.warnings.length)
      noteHtml = `<div class="fc-note warn">${e.warnings.length} parser warning(s): some blobs were skipped.</div>`;

    card.innerHTML =
      `<div class="fc-icon ${iconCls}">${iconTxt}</div>` +
      `<div class="fc-main">` +
        `<div class="fc-name">${escapeHtml(e.name)}</div>` +
        `<div class="fc-sub">${fmtSize(e.size)} ${badge}</div>` +
      `</div>` +
      `<div class="fc-status">${statusHtml}</div>` +
      `<button class="fc-remove" title="Remove" aria-label="Remove ${escapeHtml(e.name)}">×</button>` +
      noteHtml;

    card.querySelector('.fc-remove').addEventListener('click', () => removeEntry(e.id));
    fileListEl.appendChild(card);
  }
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

