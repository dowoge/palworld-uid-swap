levelInput.addEventListener('change', () => {
  if (levelInput.files && levelInput.files.length) addLevelFile(levelInput.files[0]);
  levelInput.value = '';
});
playerInput.addEventListener('change', () => {
  if (playerInput.files && playerInput.files.length) addPlayerFiles(playerInput.files);
  playerInput.value = '';
});

['dragenter', 'dragover'].forEach((ev) =>
  dropzone.addEventListener(ev, (e) => { e.preventDefault(); dropzone.classList.add('drag'); }));
['dragleave', 'dragend'].forEach((ev) =>
  dropzone.addEventListener(ev, (e) => { e.preventDefault(); if (e.target === dropzone) dropzone.classList.remove('drag'); }));
dropzone.addEventListener('drop', (e) => {
  e.preventDefault();
  dropzone.classList.remove('drag');
  if (e.dataTransfer && e.dataTransfer.files.length) addDropped(e.dataTransfer.files);
});
// Prevent the browser from navigating when a file is dropped outside the zone.
window.addEventListener('dragover', (e) => e.preventDefault());
window.addEventListener('drop', (e) => e.preventDefault());

